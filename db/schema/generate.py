"""Generate strict entity tables from the same registry used by the application."""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def registry():
    import sys

    sys.path.insert(0, str(ROOT / "packages/core/src"))
    from propadmin_core.registry import default_types

    return default_types()


def generate():
    lines = ["-- Generated by db/schema/generate.py; do not hand-edit.", "BEGIN TRANSACTION;"]
    common = {
        "name": "string",
        "description": "string DEFAULT ''",
        "aliases": "array<string> DEFAULT []",
        "evidence": "array<object> DEFAULT []",
        "created_at": "datetime DEFAULT time::now()",
        "updated_at": "datetime DEFAULT time::now()",
        "version": "int DEFAULT 1",
        "merged_into": "option<record>",
        "layout_x": "float DEFAULT 0.0",
        "layout_y": "float DEFAULT 0.0",
    }
    for table, definition in registry().items():
        lines.append(f"DEFINE TABLE OVERWRITE `{table}` SCHEMAFULL CHANGEFEED 7d INCLUDE ORIGINAL;")
        for name, kind in common.items():
            lines.append(f"DEFINE FIELD OVERWRITE `{name}` ON `{table}` TYPE {kind};")
        for name, field in definition["fields"].items():
            if name in common:
                continue
            kind = (
                field["type"].replace("text", "string").replace("option<date>", "option<datetime>")
            )
            if kind == "date":
                kind = "datetime"
            if kind.startswith("array<"):
                suffix = " DEFAULT []"
            else:
                suffix = ""
                if not field.get("required") and not kind.startswith("option<"):
                    kind = f"option<{kind}>"
            if field.get("enum") and not kind.startswith("array<"):
                suffix += " ASSERT $value = NONE OR $value IN " + json.dumps(field["enum"])
            assertions = []
            if "minimum" in field:
                assertions.append(f"$value >= {field['minimum']}")
            if "maximum" in field:
                assertions.append(f"$value <= {field['maximum']}")
            if assertions:
                clause = " AND ".join(assertions)
                suffix += (
                    (" AND (" + clause + ")")
                    if " ASSERT " in suffix
                    else " ASSERT $value = NONE OR (" + clause + ")"
                )
            if field.get("read_only"):
                suffix += " PERMISSIONS FOR update NONE"
            lines.append(f"DEFINE FIELD OVERWRITE `{name}` ON `{table}` TYPE {kind}{suffix};")
            if (table.startswith("workflow_") or table == "media_asset") and field["type"] == "object":
                lines[-1] = f"DEFINE FIELD OVERWRITE `{name}` ON `{table}` TYPE {kind} FLEXIBLE{suffix};"
            if table.startswith("workflow_") and field["type"] == "array<object>":
                lines.append(f"DEFINE FIELD OVERWRITE `{name}`.* ON `{table}` TYPE object FLEXIBLE;")
            if field.get("properties"):
                prefix = f"{name}.*" if field["type"].startswith("array<") else name
                for child, child_spec in field["properties"].items():
                    child_type = (
                        child_spec["type"]
                        .replace("text", "string")
                        .replace("option<date>", "option<datetime>")
                    )
                    if child_type == "date":
                        child_type = "datetime"
                    if not child_spec.get("required") and not child_type.startswith("option<"):
                        child_type = f"option<{child_type}>"
                    child_suffix = ""
                    if child_spec.get("enum"):
                        child_suffix += " ASSERT $value = NONE OR $value IN " + json.dumps(
                            child_spec["enum"]
                        )
                    lines.append(
                        f"DEFINE FIELD OVERWRITE {prefix}.{child} ON `{table}` TYPE {child_type}{child_suffix};"
                    )
            if field.get("unique_key") and not field["type"].startswith("array<"):
                lines.append(
                    f"DEFINE INDEX OVERWRITE `{table}_{name}_key` ON `{table}` FIELDS `{name}` UNIQUE;"
                )
        lines.extend(
            [
                f"DEFINE FIELD OVERWRITE external_ids ON `{table}` TYPE object FLEXIBLE DEFAULT {{}};",
                f"DEFINE FIELD OVERWRITE external_ids.* ON `{table}` TYPE string;",
                f"DEFINE FIELD OVERWRITE evidence.* ON `{table}` TYPE object FLEXIBLE;",
                f"DEFINE FIELD OVERWRITE external_ids.crm ON `{table}` TYPE option<string>;",
                f"DEFINE FIELD OVERWRITE external_ids.agentmail ON `{table}` TYPE option<string>;",
                f"DEFINE FIELD OVERWRITE external_ids.elevenlabs ON `{table}` TYPE option<string>;",
            ]
        )
        for index, keys in enumerate(definition.get("composite_keys", [])):
            fields = ", ".join(f"`{key}`" for key in keys)
            lines.append(
                f"DEFINE INDEX OVERWRITE `{table}_composite_{index}` ON `{table}` FIELDS {fields};"
            )
    lines.extend(
        [
            "-- Declared structured arrays retain their supported children.",
            "DEFINE FIELD OVERWRITE attachments.*.filename ON email TYPE option<string>;",
            "DEFINE FIELD OVERWRITE attachments.*.mime ON email TYPE option<string>;",
            "DEFINE FIELD OVERWRITE attachments.*.size ON email TYPE option<int>;",
            "DEFINE FIELD OVERWRITE attachments.*.gcs_uri ON email TYPE option<string>;",
            "DEFINE FIELD OVERWRITE attachments.*.document ON email TYPE option<record<source_file>>;",
            "DEFINE FIELD OVERWRITE transcript.*.turn ON call TYPE option<int>;",
            "DEFINE FIELD OVERWRITE transcript.*.speaker_role ON call TYPE option<string>;",
            "DEFINE FIELD OVERWRITE transcript.*.person ON call TYPE option<record<person>>;",
            "DEFINE FIELD OVERWRITE transcript.*.text ON call TYPE string;",
            "DEFINE FIELD OVERWRITE transcript.*.start_ms ON call TYPE option<int>;",
            "DEFINE FIELD OVERWRITE transcript.*.end_ms ON call TYPE option<int>;",
            "COMMIT TRANSACTION;",
        ]
    )
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (Path(__file__).parent / "001_entities.surql").write_text(generate())
