// Export the real gateway contract without a running server or cloud credentials.
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, readFileSync, unlinkSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import openapiTS from "openapi-typescript";
import ts from "typescript";

const root = fileURLToPath(new URL("../../../", import.meta.url));
const output = fileURLToPath(new URL("../lib/generated/", import.meta.url));
const python = [
  "import json",
  "import os",
  'os.environ["EMBEDDING_PROVIDER"] = "local"',
  'os.environ["EXTRACTION_PROVIDER"] = "local"',
  "from propadmin_core import Store",
  "from propadmin_runtime import create_app",
  "from propadmin_runtime.config import Settings",
  'app = create_app("api", store=Store(), settings=Settings(mode="local"), seed=False)',
  "print(json.dumps(app.openapi(), sort_keys=True))",
].join("\n");
const schemaFile = process.argv.find((argument) => argument.startsWith("--schema="))?.slice(9);
const schema = JSON.parse(schemaFile ? readFileSync(schemaFile, "utf8") : execFileSync("uv", ["run", "--no-sync", "python", "-c", python], {
  cwd: root,
  encoding: "utf8",
}));
// The browser uses the admin HTTP gateway; agents use the separate /mcp transport.
// New /v1 service routes gain contracts automatically on regeneration.
schema.paths = Object.fromEntries(Object.entries(schema.paths).filter(([path]) => path.startsWith("/v1/")));
const declarations = await openapiTS(schema, { alphabetize: true });
const source = ts.createSourceFile("schema.ts", "", ts.ScriptTarget.Latest);
const printer = ts.createPrinter({ removeComments: true });
const print = (node) => printer.printNode(ts.EmitHint.Unspecified, node, source);
const names = declarations.filter((node) => node.name).map((node) => node.name.text);
const generated = new Map();
const exports = [];
const header = "// Generated by pnpm generate:api. Do not edit manually.\n";

function save(name, text, ownNames = [name]) {
  const references = names.filter((other) =>
    !ownNames.includes(other) && new RegExp(`\\b${other}\\b`).test(text));
  const imports = references.length ? `import type { ${references.join(", ")} } from "./index";\n` : "";
  const content = header + imports + text + "\n";
  if (content.split("\n").length > 1000) {
    throw new Error(`${name} exceeds the 1,000-line limit; split its schema before generating`);
  }
  generated.set(`${name}.ts`, content);
}

for (const node of declarations) {
  if (!node.name) continue;
  const name = node.name.text;
  exports.push(`export type { ${name} } from "./${name}";`);
  const text = print(node);
  if (text.split("\n").length < 900 || !ts.isInterfaceDeclaration(node)) {
    save(name, text);
    continue;
  }
  // Split large route/operation interfaces by members, retaining their identities.
  const groups = [];
  let members = [];
  let lines = 0;
  const flush = () => {
    if (!members.length) return;
    const part = `${name}${groups.length + 1}`;
    save(part, `export interface ${part} {\n${members.join("\n")}\n}`);
    groups.push(part);
    members = [];
    lines = 0;
  };
  for (const member of node.members) {
    const memberText = print(member);
    const count = memberText.split("\n").length;
    if (lines + count > 700) flush();
    members.push(memberText);
    lines += count;
  }
  flush();
  const imports = groups.map((part) => `import type { ${part} } from "./${part}";`).join("\n");
  save(name, `${imports}\nexport interface ${name} extends ${groups.join(", ")} {}`);
}
generated.set("index.ts", header + exports.join("\n") + "\n");
if (process.argv.includes("--check")) {
  const stale = [...generated].filter(([file, contents]) =>
    !existsSync(output + file) || readFileSync(output + file, "utf8") !== contents);
  const extra = existsSync(output) ? readdirSync(output).filter((file) =>
    file.endsWith(".ts") && !generated.has(file)) : [];
  if (stale.length || extra.length) {
    throw new Error("API contracts are stale. Run pnpm generate:api and include the updated modules.");
  }
  console.log("Generated API contracts match the backend schema.");
  process.exit(0);
}
// Only replace generated artifacts after successful generation and size checks.
mkdirSync(output, { recursive: true });
for (const file of readdirSync(output)) {
  if (file.endsWith(".ts") && !generated.has(file)) unlinkSync(output + file);
}
for (const [file, contents] of generated) writeFileSync(output + file, contents);
console.log(`Generated ${generated.size} contract modules from ${Object.keys(schema.paths).length} API paths.`);
