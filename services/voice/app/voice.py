"""Voice adapter: ElevenLabs Agents outbound calls, inbound call briefs, server tools, post-call ingest.

ElevenLabs API shapes (docs: elevenlabs.io/docs, via Context7 /websites/elevenlabs_io):
- POST /v1/convai/{twilio|sip-trunk}/outbound-call {agent_id, agent_phone_number_id, to_number,
  conversation_initiation_client_data: {dynamic_variables}} -> {success, message, conversation_id}
- Conversation-initiation webhook body {caller_id, called_number, agent_id, call_sid, conversation_id};
  reply {type: "conversation_initiation_client_data", dynamic_variables}. Auth is a header secret
  we generate and store as an agent workspace secret, so it and the server tools send
  X-Webhook-Secret = ELEVENLABS_TOOL_SECRET.
- Post-call webhook (HMAC secret generated by ElevenLabs = ELEVENLABS_WEBHOOK_SECRET): ElevenLabs-Signature "t=<unix>,v0=<hex hmac-sha256(secret, f'{t}.{body}')>",
  rejected if older than 30 minutes (same rules as the SDK's construct_event).
"""

import hashlib
import hmac
import json
import os
import time
from datetime import UTC, datetime

import httpx
from fastapi import APIRouter, Depends, HTTPException, Request
from propadmin_core import ProviderNotConfigured
from propadmin_core.registry import normalise
from propadmin_runtime import mcp, routes_agent
from propadmin_runtime.auth import require_internal
from propadmin_runtime.services import call_service, record_action

API = "https://api.elevenlabs.io"
# Voice agent may read the graph, touch tickets and plans; merges/unlinks stay with the session.
GRAPH_TOOLS = {
    "search",
    "get_entity",
    "traverse",
    "get_document",
    "upsert_entity",
    "update_entity",
    "link_entities",
    "add_note",
}
PLAN_TOOLS = {"create_plan", "get_plan", "update_step", "add_step", "revise_plan"}
GENERIC_BRIEF = (
    "Unknown caller. Ask for their name, address and what they need; "
    "if it is a repair, get the location, urgency and access details."
)


def env(name):
    value = os.getenv(name)
    if not value:
        raise ProviderNotConfigured(f"ElevenLabs is not configured ({name})")
    return value


def stamp(unix=None):
    return datetime.fromtimestamp(unix if unix is not None else time.time(), UTC).isoformat()


def neighbours(state, entity_id):
    for edge in state["edges"].values():
        if entity_id in (edge["source"], edge["target"]):
            other = state["entities"].get(
                edge["target"] if edge["source"] == entity_id else edge["source"]
            )
            if other and not other.get("merged_into"):
                yield other


def build_brief(state, entity_id, extra=""):
    """Who, history and open items, straight from the graph. No summarisation model involved."""
    entity = state["entities"][entity_id]
    lines = [extra] if extra else []
    lines.append(f"{entity['name']} ({entity['type']}): {entity.get('description', '')}")
    for key in ("roles", "availability", "preferred_contact", "address", "status"):
        if entity["fields"].get(key):
            lines.append(f"{key}: {entity['fields'][key]}")
    seen = set()
    for other in neighbours(state, entity_id):
        if other["id"] in seen or other["type"] not in {
            "ticket",
            "company",
            "person",
            "call",
            "email",
        }:
            continue
        seen.add(other["id"])
        fields = other["fields"]
        detail = fields.get("status") or fields.get("summary") or other.get("description", "")
        lines.append(f"{other['type']} {other['name']}: {detail}")
        if len(seen) >= 12:  # ponytail: first 12 neighbours, rank by recency if briefs get noisy
            break
    return "\n".join(lines)


def phone_target(state, entity_id):
    entity = state["entities"][entity_id]
    for candidate in [entity, *neighbours(state, entity_id)]:
        if candidate["type"] in ("person", "company") and candidate["fields"].get("phones"):
            return candidate, candidate["fields"]["phones"][0]
    raise ValueError(f"No phone number on {entity_id} or its linked people")


def person_by_phone(state, number):
    try:
        number = normalise(number, {"type": "string"}, "phones")
    except ValueError:
        return None
    return next(
        (
            e
            for e in state["entities"].values()
            if e["type"] == "person"
            and not e.get("merged_into")
            and number in e["fields"].get("phones", [])
        ),
        None,
    )


def call_entity(state, conversation_id):
    return next(
        (
            e
            for e in state["entities"].values()
            if e["type"] == "call" and e["fields"].get("call_id") == conversation_id
        ),
        None,
    )


def notify_agent(app, kind, subjects, summary, data):
    try:
        return call_service(
            app.state.settings,
            "agent",
            "/internal/events",
            {"kind": kind, "subjects": subjects, "summary": summary, "data": data},
            timeout=5,
        )
    except (ProviderNotConfigured, ValueError, httpx.HTTPError) as error:
        # The call already happened; the graph keeps it even if no session can be woken.
        return {"notified": False, "error": str(error)}


def require_header_secret(request: Request):
    secret = env("ELEVENLABS_TOOL_SECRET")
    if not hmac.compare_digest(request.headers.get("x-webhook-secret", ""), secret):
        raise HTTPException(401, "Invalid webhook secret")


def verify_signature(body: bytes, header: str):
    secret = env("ELEVENLABS_WEBHOOK_SECRET")
    parts = dict(part.split("=", 1) for part in header.split(",") if "=" in part)
    try:
        fresh = int(parts["t"]) >= time.time() - 30 * 60
    except (KeyError, ValueError):
        fresh = False
    expected = hmac.new(
        secret.encode(), f"{parts.get('t')}.".encode() + body, hashlib.sha256
    ).hexdigest()
    if not fresh or not hmac.compare_digest(parts.get("v0", ""), expected):
        raise HTTPException(401, "Invalid webhook signature")


internal = APIRouter(prefix="/internal", dependencies=[Depends(require_internal)])


@internal.post("/calls")
def place_call(payload: dict, request: Request):
    app = request.app
    entity_id, objective = payload["entity_id"], payload["objective"]
    run_id = payload.get("run_id") or ""
    key, agent_id, number_id = (
        env("ELEVENLABS_API_KEY"),
        env("ELEVENLABS_AGENT_ID"),
        env("ELEVENLABS_PHONE_NUMBER_ID"),
    )
    telephony = os.getenv("ELEVENLABS_TELEPHONY", "twilio")  # or sip-trunk
    state = app.state.store.snapshot()
    target, number = phone_target(state, entity_id)
    brief = build_brief(state, target["id"], payload.get("brief", ""))
    if target["id"] != entity_id:
        brief += "\n\nAbout:\n" + build_brief(state, entity_id)
    response = httpx.post(
        f"{API}/v1/convai/{telephony}/outbound-call",
        headers={"xi-api-key": key},
        json={
            "agent_id": agent_id,
            "agent_phone_number_id": number_id,
            "to_number": number,
            "conversation_initiation_client_data": {
                "dynamic_variables": {
                    "brief": brief,
                    "objective": objective,
                    "run_id": run_id,
                    "contact_name": target["name"],
                }
            },
        },
        timeout=30,
    )
    if response.status_code >= 400:
        raise HTTPException(502, f"ElevenLabs returned HTTP {response.status_code}")
    result = response.json()
    if not result.get("success") or not result.get("conversation_id"):
        raise HTTPException(502, f"ElevenLabs did not start the call: {result.get('message')}")
    actor = f"agent_run:{run_id}" if run_id else "voice"
    call = app.state.graph.create_entity(
        {
            "type": "call",
            "name": f"Call with {target['name']}",
            "description": objective,
            "external_ids": {"elevenlabs": result["conversation_id"]},
            "fields": {
                "call_id": result["conversation_id"],
                "provider": "elevenlabs",
                "direction": "outbound",
                "to_number": number,
                "started_at": stamp(),
                "objective": objective,
                "call_brief": brief,
                "agent_session": run_id or None,
            },
        },
        actor,
        objective,
    )
    graph = app.state.graph
    graph.link_entities({"source": call["id"], "target": target["id"], "relation": "with"}, actor)
    if target["id"] != entity_id:
        graph.link_entities({"source": call["id"], "target": entity_id, "relation": "about"}, actor)
    # ponytail: registry status enum has no in-progress value; status lands with the post-call webhook
    return {"call": call, "status": "initiated", "conversation_id": result["conversation_id"]}


webhooks = APIRouter()


@webhooks.post("/webhooks/elevenlabs/initiation", dependencies=[Depends(require_header_secret)])
def initiation(payload: dict, request: Request):
    app = request.app
    state = app.state.store.snapshot()
    caller, conversation_id = payload.get("caller_id", ""), payload.get("conversation_id", "")
    person = person_by_phone(state, caller)
    brief = build_brief(state, person["id"]) if person else GENERIC_BRIEF
    subjects = [person["id"]] if person else []
    event = notify_agent(
        app,
        "call.inbound_started",
        subjects,
        f"Inbound call from {person['name'] if person else caller}",
        {"conversation_id": conversation_id, "caller_id": caller},
    )
    run_id = event.get("run_id") or ""
    if conversation_id and not call_entity(state, conversation_id):
        fields = {
            "call_id": conversation_id,
            "provider": "elevenlabs",
            "direction": "inbound",
            "started_at": stamp(),
            "call_brief": brief,
            "agent_session": run_id or None,
        }
        for name, value in (("from_number", caller), ("to_number", payload.get("called_number"))):
            try:
                fields[name] = normalise(value, {"type": "string"}, name)
            except (ValueError, TypeError):
                pass  # withheld or non-E.164 caller ids are not stored
        call = app.state.graph.create_entity(
            {
                "type": "call",
                "name": f"Inbound call from {person['name'] if person else caller or 'unknown'}",
                "external_ids": {"elevenlabs": conversation_id},
                "fields": fields,
            },
            "voice",
            "Inbound call started",
        )
        if person:
            app.state.graph.link_entities(
                {"source": call["id"], "target": person["id"], "relation": "with"}, "voice"
            )
    return {
        "type": "conversation_initiation_client_data",
        "dynamic_variables": {
            "brief": brief,
            "objective": "",
            "run_id": run_id,
            "contact_name": person["name"] if person else "",
        },
    }


@webhooks.post("/tools/voice/{name}", dependencies=[Depends(require_header_secret)])
def server_tool(name: str, payload: dict, request: Request):
    """ElevenLabs server tools call back into the owning session's tools, scoped by run_id."""
    app = request.app
    run_id = payload.pop("run_id", "")
    grant = app.state.store.snapshot().get("mcp_sessions", {}).get(run_id)
    if not run_id or not grant or grant.get("revoked"):
        raise HTTPException(403, "No active agent session for this call")
    try:
        if name in GRAPH_TOOLS:
            if "reason" in mcp.CATALOGUE[name]["inputSchema"]["properties"]:
                payload.setdefault("reason", "Requested during a voice call")
            mcp.validate(payload, mcp.CATALOGUE[name]["inputSchema"])
            result = mcp.execute(request, name, payload, run_id)
        elif name in PLAN_TOOLS and name in routes_agent.TOOLS:
            result = routes_agent.TOOLS[name]["handler"](app, run_id, payload)
        else:
            raise HTTPException(404, "Unknown voice tool")
    except Exception as error:
        record_action(app.state.store, run_id, f"voice.{name}", payload, error=str(error))
        raise
    record_action(
        app.state.store, run_id, f"voice.{name}", payload, {"ok": True}, payload.get("reason", "")
    )
    return result


@webhooks.post("/webhooks/elevenlabs/post-call")
async def post_call(request: Request):
    app = request.app
    body = await request.body()
    verify_signature(body, request.headers.get("elevenlabs-signature", ""))
    event = json.loads(body)
    if event.get("type") != "post_call_transcription":
        return {
            "status": "ignored"
        }  # ponytail: audio and initiation-failure webhooks not stored yet
    data = event["data"]
    conversation_id = data["conversation_id"]
    meta, analysis = data.get("metadata") or {}, data.get("analysis") or {}
    variables = (data.get("conversation_initiation_client_data") or {}).get(
        "dynamic_variables"
    ) or {}
    run_id = variables.get("run_id") or ""
    graph, state = app.state.graph, app.state.store.snapshot()
    existing = call_entity(state, conversation_id)
    direction = existing["fields"].get("direction", "inbound") if existing else "inbound"
    other = "caller" if direction == "inbound" else "callee"
    turns, tool_calls = [], []
    for index, turn in enumerate(data.get("transcript") or []):
        role = "agent" if turn.get("role") == "agent" else other
        tool_calls += turn.get("tool_calls") or []
        if turn.get("message"):
            turns.append(
                {
                    "turn": index,
                    "speaker_role": role,
                    "text": turn["message"],
                    "start_ms": int((turn.get("time_in_call_secs") or 0) * 1000),
                }
            )
    text = "\n".join(f"{t['speaker_role'].title()}: {t['text']}" for t in turns)
    start, duration = meta.get("start_time_unix_secs"), meta.get("call_duration_secs")
    fields = {
        "call_id": conversation_id,
        "provider": "elevenlabs",
        # ponytail: only done/failed; voicemail/no_answer/busy need telephony status mapping
        "status": "completed" if data.get("status") == "done" else "failed",
        "end_reason": meta.get("termination_reason") or None,
        "transcript": turns,
        "transcript_text": text,
        "tool_calls": tool_calls,
    }
    if start is not None:
        fields["started_at"] = stamp(start)
        if duration is not None:
            fields["ended_at"] = stamp(start + duration)
    if duration is not None:
        fields["duration_s"] = int(duration)
    if analysis.get("transcript_summary"):
        fields["summary"] = analysis["transcript_summary"]
    outcome = ((analysis.get("data_collection_results") or {}).get("outcome") or {}).get("value")
    if outcome:
        fields["outcome"] = str(outcome)
    if run_id:
        fields["agent_session"] = run_id
    record = {
        "type": "call",
        "name": existing["name"] if existing else f"Call {conversation_id}",
        "external_ids": {"elevenlabs": conversation_id},
        "fields": fields,
    }
    if existing:
        record["id"] = existing["id"]
    # One ingest updates the call by its call_id key, stores the transcript as a source file,
    # links call ->derived_from-> file and every exactly-mentioned entity.
    job = app.state.ingestion.ingest(
        {
            "filename": f"elevenlabs-{conversation_id}.txt",
            "title": record["name"],
            "mime": "text/plain",
            "origin": "elevenlabs",
            "parser": "elevenlabs-transcript",
            "text": text or None,
            "records": [record],
        }
    )
    state = app.state.store.snapshot()
    call = call_entity(state, conversation_id)
    people = [e["id"] for e in neighbours(state, call["id"]) if e["type"] == "person"]
    caller = call["fields"].get("from_number")
    if direction == "inbound" and caller and not person_by_phone(state, caller):
        person = graph.create_entity(
            {"type": "person", "name": f"Caller {caller}", "fields": {"phones": [caller]}},
            "voice",
            "Unknown inbound caller",
        )
        graph.link_entities({"source": call["id"], "target": person["id"], "relation": "with"})
        people.append(person["id"])
    agent = notify_agent(
        app,
        "call.ended",
        [call["id"], *dict.fromkeys(people)],
        fields.get("summary") or f"Call {conversation_id} ended ({fields['status']})",
        {
            "conversation_id": conversation_id,
            "call_id": call["id"],
            "run_id": run_id,
            "document_id": job["document_id"],
            "status": fields["status"],
        },
    )
    return {"call_id": call["id"], "document_id": job["document_id"], "agent": agent}
